export function buildProxyPlaybackUrl(params: {
  origin: string;
  videoId: string;
  formatId: string;
  itag: number;
  durSec: number;
  expireSec: number;
  clen: number;
  layout?: string | null;
  rev?: string | null;
  xtags?: string | null;
}): string {
  const u = new URL("/videoplayback", params.origin);
  u.searchParams.set("v", params.videoId);
  u.searchParams.set("fid", params.formatId);
  u.searchParams.set("itag", String(params.itag));
  u.searchParams.set("dur", params.durSec.toFixed(3));
  u.searchParams.set("expire", String(params.expireSec));
  if (params.clen > 0) {
    u.searchParams.set("clen", String(params.clen));
  }
  if (params.layout) {
    u.searchParams.set("layout", params.layout);
  }
  if (params.rev) {
    u.searchParams.set("rev", params.rev);
  }
  if (params.xtags) {
    u.searchParams.set("xtags", params.xtags);
  }
  return u.toString();
}

export function buildStaticDashMpdXml(
  durationSec: number,
  adaptiveFormats: AdaptiveFormatOutput[],
): string {
  const xmlEscape = (s: string) =>
    s
      .replaceAll("&", "&amp;")
      .replaceAll("<", "&lt;")
      .replaceAll(">", "&gt;")
      .replaceAll('"', "&quot;");

  const videos = adaptiveFormats.filter((f) => f.type.startsWith("video/"));
  const audios = adaptiveFormats.filter((f) => f.type.startsWith("audio/"));

  const renderRep = (f: AdaptiveFormatOutput, idx: number, isVideo: boolean): string => {
    const codecMatch = /codecs="([^"]+)"/.exec(f.type);
    const codecs = codecMatch ? codecMatch[1]! : "";
    const dims = f.size ? f.size.split("x") : [];
    const widthAttr = isVideo && dims[0] ? ` width="${dims[0]}"` : "";
    const heightAttr = isVideo && dims[1] ? ` height="${dims[1]}"` : "";
    const fpsAttr = isVideo && f.fps ? ` frameRate="${f.fps}"` : "";
    const sampleAttr = !isVideo && f.audioSampleRate ? ` audioSamplingRate="${f.audioSampleRate}"` : "";
    const audioCh = !isVideo && f.audioChannels
      ? `<AudioChannelConfiguration schemeIdUri="urn:mpeg:dash:23003:3:audio_channel_configuration:2011" value="${f.audioChannels}"/>`
      : "";

    return `      <Representation id="${xmlEscape(`${f.itag}-${idx}`)}" codecs="${xmlEscape(codecs)}" bandwidth="${xmlEscape(f.bitrate)}"${widthAttr}${heightAttr}${fpsAttr}${sampleAttr}>${audioCh}<BaseURL>${xmlEscape(f.url)}</BaseURL><SegmentBase indexRange="${xmlEscape(f.index)}"><Initialization range="${xmlEscape(f.init)}"/></SegmentBase></Representation>`;
  };

  const groupByBaseMime = (list: AdaptiveFormatOutput[]) => {
    const groups = new Map<string, AdaptiveFormatOutput[]>();
    for (const item of list) {
      const base = item.type.split(";")[0]!.trim();
      const arr = groups.get(base) || [];
      arr.push(item);
      groups.set(base, arr);
    }
    return groups;
  };

  let setId = 0;
  const sets: string[] = [];
  for (const [mime, items] of groupByBaseMime(videos)) {
    sets.push(
      `    <AdaptationSet id="${setId++}" mimeType="${xmlEscape(mime)}" subsegmentAlignment="true" startWithSAP="1">\n${items.map((f, i) => renderRep(f, i, true)).join("\n")}\n    </AdaptationSet>`,
    );
  }
  for (const [mime, items] of groupByBaseMime(audios)) {
    sets.push(
      `    <AdaptationSet id="${setId++}" mimeType="${xmlEscape(mime)}" subsegmentAlignment="true" startWithSAP="1">\n${items.map((f, i) => renderRep(f, i, false)).join("\n")}\n    </AdaptationSet>`,
    );
  }

  return [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<MPD xmlns="urn:mpeg:dash:schema:mpd:2011" profiles="urn:mpeg:dash:profile:isoff-on-demand:2011" type="static" minBufferTime="PT1.500S" mediaPresentationDuration="PT${durationSec.toFixed(3)}S">`,
    `  <Period>`,
    ...sets,
    `  </Period>`,
    `</MPD>`,
  ].join("\n");
}

