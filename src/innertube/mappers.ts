export function escapeHtml(input: string): string {
  return input
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

export function descriptionToHtml(text: string): string {
  if (!text) return "";
  const escaped = escapeHtml(text);
  // Linkify URLs without swallowing trailing HTML entities (&lt;, &gt;, &quot;, &#39;)
  const withUrls = escaped.replace(
    /\bhttps?:\/\/(?:[^\s<>&"']|&(?!lt;|gt;|quot;|#39;))+/g,
    (url) => `<a href="${url}" target="_blank" rel="noopener noreferrer">${url}</a>`,
  );
  return withUrls.replace(/\r?\n/g, "<br>");
}

export function textOf(node: unknown): string {
  if (node === null || node === undefined) return "";
  if (typeof node === "string") return node;
  if (typeof node === "number") return String(node);
  if (typeof node === "object") {
    const obj = node as Record<string, unknown>;
    if (typeof obj.text === "string") return obj.text;
    if (typeof obj.toString === "function" && obj.toString !== Object.prototype.toString) {
      const s = obj.toString();
      if (s && s !== "[object Object]") return s;
    }
    if (Array.isArray(obj.runs)) {
      return obj.runs.map((r) => (typeof r?.text === "string" ? r.text : "")).join("");
    }
  }
  return "";
}

export function normalizeHttpsUrl(url: string | undefined | null): string {
  if (!url) return "";
  const trimmed = url.trim();
  if (trimmed.startsWith("//")) return `https:${trimmed}`;
  return trimmed;
}

/**
 * Rewrite YouTube image host URLs so FreeTube fetches them through our IPv4 proxy.
 */
export function rewriteImageToOrigin(url: string, origin: string): string {
  const normalized = normalizeHttpsUrl(url);
  if (!normalized) return "";
  if (normalized.startsWith(origin)) return normalized;
  return normalized
    .replace(/^https:\/\/yt3\.ggpht\.com/, `${origin}/ggpht`)
    .replace(/^https:\/\/yt3\.googleusercontent\.com/, `${origin}/ggpht`)
    .replace(/^https:\/\/i\d*\.ytimg\.com/, `${origin}/ggpht`);
}

/**
 * FreeTube 0.26.0 directly indexes:
 * - authorThumbnails[0] (subscription icon)
 * - authorThumbnails[1] (WatchVideo)
 * - authorThumbnails[2] (FtListChannel, PlaylistView)
 * - authorThumbnails[3] (ChannelView!)
 * Always guarantee at least 4 entries sorted from smallest to largest.
 */
export function normalizeAuthorThumbnails(
  raw: Array<{ url?: string; width?: number; height?: number }> | string | undefined | null,
  origin?: string,
): InvidiousThumbnail[] {
  const sizes = [32, 48, 76, 176];
  const parsed: InvidiousThumbnail[] = [];

  if (typeof raw === "string" && raw.trim()) {
    const base = origin ? rewriteImageToOrigin(raw, origin) : normalizeHttpsUrl(raw);
    return sizes.map((s) => ({
      url: base.replace(/=s\d+/, `=s${s}`),
      width: s,
      height: s,
    }));
  }

  if (Array.isArray(raw)) {
    for (const item of raw) {
      if (!item?.url) continue;
      const u = origin ? rewriteImageToOrigin(item.url, origin) : normalizeHttpsUrl(item.url);
      if (!u) continue;
      parsed.push({
        url: u,
        width: Number(item.width) || 88,
        height: Number(item.height) || 88,
      });
    }
  }

  if (parsed.length === 0) {
    // Safe fallback so FreeTube never throws on index access
    const fallbackUrl = origin ? `${origin}/ggpht/ytc/default_avatar=s88-c-k-c0x00ffffff-no-rj` : "";
    return sizes.map((s) => ({ url: fallbackUrl, width: s, height: s }));
  }

  parsed.sort((a, b) => a.width - b.width);

  // Pad up to 4 entries by resizing/duplicating the highest-res available avatar
  const best = parsed[parsed.length - 1]!;
  while (parsed.length < 4) {
    const targetSize = sizes[parsed.length] ?? 176;
    const resizedUrl = /=s\d+/.test(best.url)
      ? best.url.replace(/=s\d+/, `=s${targetSize}`)
      : best.url;
    parsed.push({ url: resizedUrl, width: targetSize, height: targetSize });
  }

  return parsed;
}

export function buildVideoThumbnails(videoId: string, origin: string): InvidiousThumbnail[] {
  const base = `${origin}/vi/${encodeURIComponent(videoId)}`;
  return [
    { quality: "maxresdefault", url: `${base}/maxresdefault.jpg`, width: 1280, height: 720 },
    { quality: "sddefault", url: `${base}/sddefault.jpg`, width: 640, height: 480 },
    { quality: "high", url: `${base}/hqdefault.jpg`, width: 480, height: 360 },
    { quality: "medium", url: `${base}/mqdefault.jpg`, width: 320, height: 180 },
    { quality: "default", url: `${base}/default.jpg`, width: 120, height: 90 },
  ];
}

export function parseCompactNumber(input: unknown): number {
  if (typeof input === "number" && Number.isFinite(input)) return Math.round(input);
  const str = textOf(input).trim();
  if (!str) return 0;

  // Match e.g. "1.23M", "45,678", "920K", "2.1B"
  const match = /([\d,.]+)\s*([KMBT])?\b/i.exec(str);
  if (!match) return 0;
  const rawNum = match[1]!;
  const suffix = (match[2] || "").toUpperCase();

  let num: number;
  if (suffix) {
    // "1,2M" (European) or "1.2M"
    num = parseFloat(rawNum.replace(",", "."));
  } else {
    num = parseFloat(rawNum.replace(/,/g, ""));
  }
  if (!Number.isFinite(num)) return 0;

  const mult =
    suffix === "K"
      ? 1e3
      : suffix === "M"
        ? 1e6
        : suffix === "B"
          ? 1e9
          : suffix === "T"
            ? 1e12
            : 1;
  return Math.round(num * mult);
}

export function formatCompactCount(count: number): string {
  if (!Number.isFinite(count) || count <= 0) return "";
  if (count >= 1e9) return `${(count / 1e9).toFixed(2).replace(/\.?0+$/, "")}B`;
  if (count >= 1e6) return `${(count / 1e6).toFixed(2).replace(/\.?0+$/, "")}M`;
  if (count >= 1e3) return `${(count / 1e3).toFixed(1).replace(/\.?0+$/, "")}K`;
  return String(Math.round(count));
}

export function parseDurationTextToSeconds(input: unknown): number {
  if (typeof input === "number" && Number.isFinite(input)) return Math.max(0, Math.round(input));
  const str = textOf(input).trim();
  if (!str) return 0;
  const parts = str.split(":").map((p) => Number(p.trim()));
  if (parts.some((p) => !Number.isFinite(p))) return 0;
  if (parts.length === 3) return parts[0]! * 3600 + parts[1]! * 60 + parts[2]!;
  if (parts.length === 2) return parts[0]! * 60 + parts[1]!;
  if (parts.length === 1) return parts[0]!;
  return 0;
}

export function parseRelativeTimeToUnixSec(input: unknown, nowMs = Date.now()): number {
  if (typeof input === "number" && Number.isFinite(input)) {
    return input > 1e12 ? Math.floor(input / 1000) : Math.floor(input);
  }
  const str = textOf(input).trim();
  if (!str) return Math.floor(nowMs / 1000);

  const lower = str.toLowerCase();
  if (lower === "just now" || lower === "today") {
    return Math.floor(nowMs / 1000);
  }
  if (lower === "yesterday") {
    return Math.max(0, Math.floor(nowMs / 1000) - 86400);
  }

  // Try ISO / absolute date first (e.g. "Jan 15, 2024" or "2024-01-15")
  if (!/\bago\b/i.test(str) && /\d{4}/.test(str)) {
    const parsed = Date.parse(str.replace(/^(Premiered|Streamed|Joined)\s+/i, ""));
    if (!Number.isNaN(parsed)) {
      return Math.floor(parsed / 1000);
    }
  }

  // Match both full ("4 days ago", "2 months ago") and YouTube 2026 compact ("4d ago", "3mo ago", "2h ago", "1y ago")
  const m = /(\d+)\s*(seconds?|secs?|s|minutes?|mins?|m|hours?|hrs?|h|days?|d|weeks?|wks?|w|months?|mos?|mo|years?|yrs?|y)\s+ago/i.exec(
    str,
  );
  if (!m) return Math.floor(nowMs / 1000);

  const amount = Number(m[1]);
  const rawUnit = m[2]!.toLowerCase();
  let unitSeconds = 0;
  if (rawUnit === "s" || rawUnit.startsWith("sec")) unitSeconds = 1;
  else if (rawUnit === "mo" || rawUnit.startsWith("mon") || rawUnit === "mos") unitSeconds = 30 * 86400;
  else if (rawUnit === "m" || rawUnit.startsWith("min")) unitSeconds = 60;
  else if (rawUnit === "h" || rawUnit.startsWith("h")) unitSeconds = 3600;
  else if (rawUnit === "d" || rawUnit.startsWith("day")) unitSeconds = 86400;
  else if (rawUnit === "w" || rawUnit.startsWith("w")) unitSeconds = 7 * 86400;
  else if (rawUnit === "y" || rawUnit.startsWith("y")) unitSeconds = 365 * 86400;

  return Math.max(0, Math.floor(nowMs / 1000) - amount * unitSeconds);
}

export function parseUploadDateToUnixSec(uploadDate?: string, timestamp?: number): number {
  if (typeof timestamp === "number" && Number.isFinite(timestamp) && timestamp > 0) {
    return timestamp > 1e12 ? Math.floor(timestamp / 1000) : Math.floor(timestamp);
  }
  if (uploadDate && /^\d{8}$/.test(uploadDate)) {
    const y = uploadDate.slice(0, 4);
    const m = uploadDate.slice(4, 6);
    const d = uploadDate.slice(6, 8);
    const ms = Date.parse(`${y}-${m}-${d}T00:00:00Z`);
    if (!Number.isNaN(ms)) return Math.floor(ms / 1000);
  }
  return Math.floor(Date.now() / 1000);
}

/**
 * Extract video card data from any youtubei.js video-like node
 * (Video, CompactVideo, GridVideo, PlaylistVideo, LockupView).
 */
export function mapYoutubeiVideoNode(
  rawNode: unknown,
  origin: string,
  fallbackChannel?: { author: string; authorId: string },
): InvidiousVideoCard | null {
  if (!rawNode || typeof rawNode !== "object") return null;
  const node = rawNode as Record<string, any>;
  const nodeType = String(node.type || "");

  // Handle modern ShortsLockupView nodes (channel Shorts tab / playlists)
  if (nodeType === "ShortsLockupView") {
    const videoId = String(
      node.on_tap_endpoint?.payload?.videoId ||
      (typeof node.entity_id === "string" ? node.entity_id.replace(/^shorts-shelf-item-/, "") : ""),
    );
    if (!videoId || videoId.length < 6) return null;
    const title = textOf(node.overlay_metadata?.primary_text || node.accessibility_text);
    const viewText = textOf(node.overlay_metadata?.secondary_text);
    return {
      type: "video",
      title,
      videoId,
      author: fallbackChannel?.author || "",
      authorId: fallbackChannel?.authorId || "",
      authorUrl: fallbackChannel?.authorId ? `/channel/${fallbackChannel.authorId}` : "",
      videoThumbnails: buildVideoThumbnails(videoId, origin),
      description: "",
      descriptionHtml: "",
      viewCount: parseCompactNumber(viewText),
      viewCountText: viewText,
      published: Math.floor(Date.now() / 1000),
      publishedText: "",
      lengthSeconds: 0,
      liveNow: false,
      premium: false,
      isUpcoming: false,
    };
  }

  // Handle newer LockupView nodes (youtubei.js v14+)
  if (nodeType === "LockupView") {
    if (node.content_type && node.content_type !== "VIDEO") return null;
    const videoId = String(node.content_id || "");
    if (!videoId) return null;
    const title = textOf(node.metadata?.title);
    const metadataRows: any[] = node.metadata?.metadata?.metadata_rows || [];
    const firstRowParts: any[] = metadataRows[0]?.metadata_parts || [];
    const secondRowParts: any[] = metadataRows[1]?.metadata_parts || [];

    const isTimeLike = (s: string) =>
      /\bago\b|\byesterday\b|\btoday\b|\bjust now\b/i.test(s) ||
      /^(Premiered|Streamed)\s/i.test(s);
    const isCountLike = (s: string) =>
      /^no views$/i.test(s.trim()) ||
      /^[\d,.]+\s*[KMBT]?(\s+(views?|watching))?$/i.test(s.trim());

    let author = fallbackChannel?.author || "";
    let authorBrowseId = fallbackChannel?.authorId || "";
    let statsParts: any[] = [];

    if (metadataRows.length >= 2) {
      author = textOf(firstRowParts[0]?.text) || author;
      authorBrowseId =
        firstRowParts[0]?.text?.endpoint?.payload?.browseId ||
        node.metadata?.image?.renderer_context?.command_context?.on_tap?.innertubeCommand?.browseEndpoint?.browseId ||
        authorBrowseId;
      statsParts = secondRowParts;
    } else if (firstRowParts.length > 0) {
      // Channel-page LockupView has a single metadata row like ["1.7M", "1d ago"] (no author row)
      const p0 = textOf(firstRowParts[0]?.text).trim();
      const p1 = textOf(firstRowParts[1]?.text).trim();
      const looksLikeStatsRow =
        Boolean(fallbackChannel?.author) || isCountLike(p0) || isTimeLike(p0) || isTimeLike(p1);
      if (looksLikeStatsRow) {
        statsParts = firstRowParts;
      } else {
        author = p0 || author;
        authorBrowseId = firstRowParts[0]?.text?.endpoint?.payload?.browseId || authorBrowseId;
        statsParts = firstRowParts.slice(1);
      }
    }

    let viewText = "";
    let pubText = "";
    for (const part of statsParts) {
      const txt = textOf(part?.text).trim();
      if (!txt) continue;
      if (!pubText && isTimeLike(txt)) {
        pubText = txt;
      } else if (!viewText && isCountLike(txt)) {
        viewText = txt;
      }
    }

    // Duration badge inside content_image overlays
    let durationSec = 0;
    const overlays: any[] = node.content_image?.overlays || [];
    for (const ov of overlays) {
      const badges: any[] = ov?.badges || [];
      for (const b of badges) {
        const t = textOf(b?.text);
        if (/^\d+:\d+/.test(t)) {
          durationSec = parseDurationTextToSeconds(t);
          break;
        }
      }
    }

    return {
      type: "video",
      title,
      videoId,
      author,
      authorId: String(authorBrowseId || ""),
      authorUrl: authorBrowseId ? `/channel/${authorBrowseId}` : "",
      videoThumbnails: buildVideoThumbnails(videoId, origin),
      description: "",
      descriptionHtml: "",
      viewCount: parseCompactNumber(viewText),
      viewCountText: viewText,
      published: parseRelativeTimeToUnixSec(pubText),
      publishedText: pubText,
      lengthSeconds: durationSec,
      liveNow: false,
      premium: false,
      isUpcoming: false,
    };
  }

  // Standard Video / CompactVideo / GridVideo / PlaylistVideo
  const videoId = String(node.id || node.video_id || "");
  if (!videoId || videoId.length < 6) return null;

  const title = textOf(node.title);
  const authorObj = node.author && typeof node.author === "object" ? node.author : null;
  const author =
    textOf(authorObj?.name) ||
    (typeof node.author === "string" ? node.author : "") ||
    fallbackChannel?.author ||
    "";
  const authorId =
    String(authorObj?.id || authorObj?.endpoint?.payload?.browseId || fallbackChannel?.authorId || "");

  const durationSec =
    typeof node.duration?.seconds === "number"
      ? node.duration.seconds
      : parseDurationTextToSeconds(node.duration?.text ?? node.length_text ?? node.duration);

  const viewText =
    textOf(node.short_view_count) ||
    textOf(node.view_count) ||
    textOf(node.views) ||
    "";
  const viewCount = parseCompactNumber(textOf(node.view_count) || viewText);

  const publishedText = textOf(node.published) || textOf(node.published_time) || "";
  const published = parseRelativeTimeToUnixSec(publishedText);
  const description = textOf(node.description_snippet) || textOf(node.snippets?.[0]?.text) || "";

  const isLive = Boolean(node.is_live);
  const isUpcoming = Boolean(node.is_upcoming);

  return {
    type: "video",
    title,
    videoId,
    author,
    authorId,
    authorUrl: authorId ? `/channel/${authorId}` : "",
    videoThumbnails: buildVideoThumbnails(videoId, origin),
    description,
    descriptionHtml: descriptionToHtml(description),
    viewCount,
    viewCountText: viewText,
    published,
    publishedText,
    lengthSeconds: durationSec,
    liveNow: isLive,
    premium: false,
    isUpcoming,
  };
}

export function mapYoutubeiChannelCard(
  rawNode: unknown,
  origin: string,
): InvidiousChannelCard | null {
  if (!rawNode || typeof rawNode !== "object") return null;
  const node = rawNode as Record<string, any>;
  const authorId = String(node.id || node.author?.id || node.endpoint?.payload?.browseId || "");
  if (!authorId) return null;

  const author = textOf(node.author?.name || node.title || node.author);
  const rawHandle = textOf(node.subscriber_count);
  const videoCountText = textOf(node.video_count);

  // YouTube sometimes puts @handle in subscriber_count and subCount in video_count
  let channelHandle: string | undefined;
  let subCount = 0;
  let videoCount = 0;

  if (rawHandle.startsWith("@")) {
    channelHandle = rawHandle;
    subCount = parseCompactNumber(videoCountText);
  } else {
    subCount = parseCompactNumber(rawHandle);
    videoCount = parseCompactNumber(videoCountText);
  }

  const rawThumbs = node.author?.thumbnails || node.thumbnails || [];
  const description = textOf(node.description_snippet);

  return {
    type: "channel",
    author,
    authorId,
    authorUrl: `/channel/${authorId}`,
    ...(channelHandle ? { channelHandle } : {}),
    authorVerified: Boolean(node.author?.is_verified),
    authorThumbnails: normalizeAuthorThumbnails(rawThumbs, origin),
    autoGenerated: false,
    subCount,
    videoCount,
    description,
    descriptionHtml: descriptionToHtml(description),
  };
}

export function mapYoutubeiPlaylistCard(
  rawNode: unknown,
  origin: string,
  fallbackChannel?: { author: string; authorId: string },
): InvidiousPlaylistCard | null {
  if (!rawNode || typeof rawNode !== "object") return null;
  const node = rawNode as Record<string, any>;
  const nodeType = String(node.type || "");

  if (nodeType === "LockupView") {
    if (node.content_type && !["PLAYLIST", "PODCAST", "ALBUM", "COURSE"].includes(node.content_type)) {
      return null;
    }
    const playlistId = String(node.content_id || "");
    if (!playlistId) return null;
    const title = textOf(node.metadata?.title);
    const metadataRows: any[] = node.metadata?.metadata?.metadata_rows || [];
    const firstPart = metadataRows[0]?.metadata_parts?.[0];
    const author = textOf(firstPart?.text) || fallbackChannel?.author || "";
    const authorId =
      String(firstPart?.text?.endpoint?.payload?.browseId || fallbackChannel?.authorId || "");

    const rawThumb =
      node.content_image?.primary_thumbnail?.image?.[0]?.url ||
      node.content_image?.image?.[0]?.url ||
      "";
    let videoCount = 0;
    const overlays: any[] =
      node.content_image?.primary_thumbnail?.overlays || node.content_image?.overlays || [];
    for (const ov of overlays) {
      for (const b of ov?.badges || []) {
        const count = parseCompactNumber(b?.text);
        if (count > 0) {
          videoCount = count;
          break;
        }
      }
    }

    return {
      type: "playlist",
      title,
      playlistId,
      playlistThumbnail: rawThumb ? rewriteImageToOrigin(rawThumb, origin) : "",
      author,
      authorId,
      authorUrl: authorId ? `/channel/${authorId}` : "",
      authorVerified: false,
      videoCount,
      videos: [],
    };
  }

  const playlistId = String(node.id || node.playlist_id || "");
  if (!playlistId) return null;
  const title = textOf(node.title);
  const author = textOf(node.author?.name || node.author) || fallbackChannel?.author || "";
  const authorId = String(node.author?.id || fallbackChannel?.authorId || "");
  const rawThumb =
    (Array.isArray(node.thumbnails) && node.thumbnails[0]?.url) ||
    (node.first_videos?.[0]?.id ? `${origin}/vi/${node.first_videos[0].id}/mqdefault.jpg` : "");

  const videoCount = parseCompactNumber(node.video_count || node.video_count_short);

  const previewVideos: InvidiousPlaylistCard["videos"] = [];
  if (Array.isArray(node.videos)) {
    for (const v of node.videos) {
      const vid = String(v?.id || "");
      if (!vid) continue;
      previewVideos.push({
        title: textOf(v.title),
        videoId: vid,
        lengthSeconds: parseDurationTextToSeconds(v.duration?.seconds ?? v.duration),
        videoThumbnails: buildVideoThumbnails(vid, origin),
      });
    }
  }

  return {
    type: "playlist",
    title,
    playlistId,
    playlistThumbnail: rawThumb ? rewriteImageToOrigin(rawThumb, origin) : "",
    author,
    authorId,
    authorUrl: authorId ? `/channel/${authorId}` : "",
    authorVerified: Boolean(node.author?.is_verified),
    videoCount,
    videos: previewVideos,
  };
}

export function mapSearchResultNode(node: unknown, origin: string): InvidiousSearchItem | null {
  if (!node || typeof node !== "object") return null;
  const obj = node as Record<string, any>;
  const t = String(obj.type || "");

  if (t === "Video" || t === "CompactVideo" || t === "GridVideo") {
    return mapYoutubeiVideoNode(obj, origin);
  }
  if (t === "Channel") {
    return mapYoutubeiChannelCard(obj, origin);
  }
  if (t === "Playlist" || t === "GridPlaylist" || t === "CompactPlaylist") {
    return mapYoutubeiPlaylistCard(obj, origin);
  }
  if (t === "LockupView") {
    if (obj.content_type === "VIDEO") return mapYoutubeiVideoNode(obj, origin);
    if (["PLAYLIST", "PODCAST", "ALBUM", "COURSE"].includes(String(obj.content_type || ""))) {
      return mapYoutubeiPlaylistCard(obj, origin);
    }
  }
  return null;
}

export function mapChannelHeaderAndMeta(
  channel: Record<string, any>,
  fallbackId: string,
  origin: string,
) {
  const meta = channel.metadata || {};
  const header = channel.header || {};

  const authorId = String(meta.external_id || header.id || fallbackId);
  const author = textOf(meta.title || header.author?.name || header.content?.title?.text || "");
  const description = textOf(meta.description || "");

  // Extract avatar thumbnails from PageHeader, C4TabbedHeader, or metadata
  const rawAvatars: Array<{ url?: string; width?: number; height?: number }> =
    header.content?.image?.avatar?.image ||
    header.author?.thumbnails ||
    meta.avatar ||
    meta.thumbnail ||
    [];

  // Extract banner thumbnails
  const rawBanners: Array<{ url?: string; width?: number; height?: number }> =
    header.content?.banner?.image ||
    header.banner ||
    [];

  // Extract subscriber count from PageHeader metadata rows or C4TabbedHeader
  let subCount = 0;
  if (header.subscribers) {
    subCount = parseCompactNumber(header.subscribers);
  } else if (Array.isArray(header.content?.metadata?.metadata_rows)) {
    for (const row of header.content.metadata.metadata_rows) {
      for (const part of row?.metadata_parts || []) {
        const txt = textOf(part?.text);
        if (/subscriber/i.test(txt)) {
          subCount = parseCompactNumber(txt);
        }
      }
    }
  }

  // Normalize available channel tabs to Invidious tab names
  const rawTabs: string[] = Array.isArray(channel.tabs)
    ? channel.tabs.map((t: unknown) => String(t).toLowerCase())
    : [];
  const tabs: string[] = [];
  for (const tab of rawTabs) {
    if (tab === "home") tabs.push("home");
    else if (tab === "videos") tabs.push("videos");
    else if (tab === "shorts") tabs.push("shorts");
    else if (tab === "live") tabs.push("streams");
    else if (tab === "podcasts") tabs.push("podcasts");
    else if (tab === "releases") tabs.push("releases");
    else if (tab === "courses") tabs.push("courses");
    else if (tab === "playlists") tabs.push("playlists");
    // Omit "posts"/"community" until community post fetching is implemented
  }
  if (!tabs.includes("videos")) tabs.unshift("videos");

  return {
    author,
    authorId,
    authorUrl: `/channel/${authorId}`,
    authorBanners: rawBanners
      .filter((b) => Boolean(b?.url))
      .map((b) => ({
        url: rewriteImageToOrigin(b.url!, origin),
        width: Number(b.width) || 2560,
        height: Number(b.height) || 424,
      })),
    authorThumbnails: normalizeAuthorThumbnails(rawAvatars, origin),
    subCount,
    totalViews: 0,
    joined: 0,
    autoGenerated: false,
    isFamilyFriendly: meta.is_family_safe !== false,
    description,
    descriptionHtml: descriptionToHtml(description),
    allowedRegions: [],
    tabs,
    tags: Array.isArray(meta.keywords) ? meta.keywords : [],
    authorVerified: false,
    latestVideos: [],
    relatedChannels: [],
  };
}

export function mapCommentThreadToInvidious(
  thread: Record<string, any>,
  origin: string,
  replyContinuationToken?: string,
): InvidiousComment | null {
  const comment = thread.comment || thread;
  if (!comment || typeof comment !== "object") return null;

  const commentId = String(comment.comment_id || comment.id || "");
  if (!commentId) return null;

  const authorObj = comment.author || {};
  const author = textOf(authorObj.name || comment.author_text || "");
  const authorId = String(authorObj.id || authorObj.endpoint?.payload?.browseId || "");
  const rawThumbs = authorObj.thumbnails || [];
  const authorThumbnails = normalizeAuthorThumbnails(rawThumbs, origin);
  const primaryThumb = authorThumbnails[1]?.url || authorThumbnails[0]?.url || "";

  const content = textOf(comment.content);
  const publishedText = textOf(comment.published_time || comment.published);
  const likeCount = parseCompactNumber(comment.like_count ?? comment.vote_count);
  const replyCount = parseCompactNumber(comment.reply_count ?? thread.replies?.reply_count ?? 0);

  const isPinned = Boolean(comment.is_pinned);
  const isOwner = Boolean(comment.author_is_channel_owner);
  const isHearted = Boolean(comment.is_hearted);
  const isMember = Boolean(comment.is_member);
  const memberIconUrl = comment.member_badge?.url
    ? rewriteImageToOrigin(String(comment.member_badge.url), origin)
    : undefined;

  const mapped: InvidiousComment = {
    author,
    authorThumbnails,
    authorThumbnail: primaryThumb,
    authorId,
    authorUrl: authorId ? `/channel/${authorId}` : "",
    isEdited: /\(edited\)/i.test(publishedText),
    isPinned,
    isSponsor: isMember,
    ...(memberIconUrl ? { sponsorIconUrl: memberIconUrl } : {}),
    content,
    contentHtml: descriptionToHtml(content),
    published: parseRelativeTimeToUnixSec(publishedText),
    publishedText,
    likeCount,
    commentId,
    authorIsChannelOwner: isOwner,
  };

  if (isHearted) {
    mapped.creatorHeart = {
      creatorThumbnail: "",
      creatorName: "",
    };
  }

  if (replyCount > 0 && replyContinuationToken) {
    mapped.replies = {
      replyCount,
      continuation: replyContinuationToken,
    };
  }

  return mapped;
}

export function buildStoryboardWebVtt(
  boards: Array<{
    template_url: string;
    thumbnail_width: number;
    thumbnail_height: number;
    thumbnail_count: number;
    interval: number;
    columns: number;
    rows: number;
    storyboard_count?: number;
  }>,
  durationSec: number,
  targetHeight: number,
  origin: string,
): string {
  if (!boards || boards.length === 0 || durationSec <= 0) {
    return "WEBVTT\n\n";
  }

  // Pick board closest to requested height (usually 90px in FreeTube)
  const chosen = [...boards].sort(
    (a, b) => Math.abs(a.thumbnail_height - targetHeight) - Math.abs(b.thumbnail_height - targetHeight),
  )[0]!;

  const perSheet = chosen.columns * chosen.rows;
  if (perSheet <= 0 || chosen.thumbnail_count <= 0) return "WEBVTT\n\n";

  const sheetCount = Math.ceil(chosen.thumbnail_count / perSheet);
  const stepSec = chosen.interval > 0 ? chosen.interval / 1000 : durationSec / (sheetCount * perSheet);

  const fmtTime = (totalSec: number): string => {
    const hrs = Math.floor(totalSec / 3600);
    const mins = Math.floor((totalSec % 3600) / 60);
    const secs = totalSec % 60;
    return `${String(hrs).padStart(2, "0")}:${String(mins).padStart(2, "0")}:${secs.toFixed(3).padStart(6, "0")}`;
  };

  let vtt = "WEBVTT\n\n";
  let currentSec = 0;
  let rendered = 0;

  for (let sheet = 0; sheet < sheetCount; sheet++) {
    const rawSheetUrl = chosen.template_url.replace("$M", String(sheet));
    const sheetUrl = rewriteImageToOrigin(rawSheetUrl, origin);
    let x = 0;
    let y = 0;

    for (let i = 0; i < perSheet && rendered < chosen.thumbnail_count; i++) {
      const nextSec = currentSec + stepSec;
      vtt += `${fmtTime(currentSec)} --> ${fmtTime(nextSec)}\n`;
      vtt += `${sheetUrl}#xywh=${x},${y},${chosen.thumbnail_width},${chosen.thumbnail_height}\n\n`;
      currentSec = nextSec;
      rendered++;
      x += chosen.thumbnail_width;
      if (x >= chosen.thumbnail_width * chosen.columns) {
        x = 0;
        y += chosen.thumbnail_height;
      }
    }
  }

  return vtt;
}

export function buildMimeTypeFromYtDlp(format: {
  ext?: string;
  container?: string;
  vcodec?: string | null;
  acodec?: string | null;
}): string {
  const hasVideo = Boolean(format.vcodec && format.vcodec !== "none");
  const hasAudio = Boolean(format.acodec && format.acodec !== "none");
  const isWebm = format.ext === "webm" || format.container === "webm_dash";

  const codecs: string[] = [];
  if (hasVideo && format.vcodec) codecs.push(format.vcodec);
  if (hasAudio && format.acodec) codecs.push(format.acodec);
  const codecPart = codecs.length > 0 ? `; codecs="${codecs.join(", ")}"` : "";

  if (hasVideo) {
    const container = isWebm ? "video/webm" : "video/mp4";
    return `${container}${codecPart}`;
  }
  const container = isWebm ? "audio/webm" : "audio/mp4";
  return `${container}${codecPart}`;
}

export function inferAudioQuality(abrKbps?: number | null, formatNote?: string | null): string {
  const note = (formatNote || "").toLowerCase();
  if (note.includes("high")) return "AUDIO_QUALITY_HIGH";
  if (note.includes("low")) return "AUDIO_QUALITY_LOW";
  if (note.includes("medium")) return "AUDIO_QUALITY_MEDIUM";
  if (abrKbps && abrKbps >= 160) return "AUDIO_QUALITY_HIGH";
  if (abrKbps && abrKbps < 70) return "AUDIO_QUALITY_LOW";
  return "AUDIO_QUALITY_MEDIUM";
}

